// ─── LinkedTipText: scans tip text and turns product keywords into Amazon links ──
function LinkedTipText({ text }) {
  if (!text) return null;

  // Build a regex from all phrases, longest-first to prevent shorter matches eating longer ones
  const sorted = [...TIP_KEYWORDS].sort((a, b) => b.phrase.length - a.phrase.length);
  const pattern = new RegExp(
    `(${sorted.map(k => k.phrase.replace(/[.*+?^${}()|[\]\\]/g, "\\$&")).join("|")})`,
    "gi"
  );

  const parts = text.split(pattern);
  const linkedPhrases = new Set(); // de-dupe: only first occurrence becomes a link

  return (
    <>
      {parts.map((part, i) => {
        const matchedKw = sorted.find(k => k.phrase.toLowerCase() === part.toLowerCase());
        if (matchedKw && !linkedPhrases.has(matchedKw.phrase.toLowerCase())) {
          linkedPhrases.add(matchedKw.phrase.toLowerCase());
          return (
            <a key={i}
              href={amazonLink(matchedKw.query)}
              target="_blank"
              rel="noopener noreferrer"
              style={{
                color: "#FF9900",
                fontWeight: 800,
                textDecoration: "underline",
                textDecorationStyle: "dotted",
                textUnderlineOffset: "3px",
              }}>
              {part}
            </a>
          );
        }
        return <span key={i}>{part}</span>;
      })}
    </>
  );
}

