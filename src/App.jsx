// ─── Price range helpers ─────────────────────────────────────────────────────
// Items may have either {unitCostLow, unitCostHigh} (preferred) or {unitCost} (legacy).
// These helpers normalize both shapes so the rest of the code doesn't care.
const itemLow  = (it) => Number(it.unitCostLow  ?? it.unitCost ?? 0);
const itemHigh = (it) => Number(it.unitCostHigh ?? it.unitCost ?? 0);
const itemMid  = (it) => (itemLow(it) + itemHigh(it)) / 2;
const itemMidCost = (it) => itemMid(it) * Number(it.quantity || 1);

// Display string like "$0.40–0.65" or "$0.50" if low === high
const itemPriceLabel = (it) => {
  const lo = itemLow(it), hi = itemHigh(it);
  if (lo === hi) return `~$${lo.toFixed(2)}`;
  return `$${lo.toFixed(2)}–${hi.toFixed(2)}`;
};

// Bag total range: sum of (low × qty) to sum of (high × qty)
const bagTotalRange = (items = []) => {
  const low  = items.reduce((s, it) => s + itemLow(it)  * Number(it.quantity || 1), 0);
  const high = items.reduce((s, it) => s + itemHigh(it) * Number(it.quantity || 1), 0);
  return { low, high, mid: (low + high) / 2 };
};

