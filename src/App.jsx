// ─── Validation (lightweight client-side guardrails) ──────────────────────────
const BANNED_KEYWORDS = ["gum","chewing gum","latex","peanut"];

function validateBag(bag, form) {
  const errors = [];
  const budget = parseFloat(form.budget);

  if (!bag.items || bag.items.length < 4) errors.push("Too few items");

  // Use midpoint sum for budget check (the displayed "expected" total)
  const { mid } = bagTotalRange(bag.items || []);
  if (mid > budget * 1.05) errors.push("Over budget");

  // Banned keyword scan
  for (const item of bag.items || []) {
    const txt = `${item.name} ${item.description}`.toLowerCase();
    for (const kw of BANNED_KEYWORDS) {
      // Skip nut-related blocks if school-safe/nut-free is not selected
      if (kw === "peanut" && !form.allergies.includes("nut_free") && !form.allergies.includes("school_safe")) continue;
      if (txt.includes(kw)) errors.push(`Banned keyword "${kw}" in ${item.name}`);
    }
  }

  // Hero item check (must have at least one)
  const hasHero = (bag.items || []).some(i => i.category === "hero");
  if (!hasHero) errors.push("Missing hero item");

  // Bag-as-item check (must be first item)
  const firstIsBag = bag.items?.[0]?.category === "bag";
  if (!firstIsBag) errors.push("Bag not included as first item");

  return errors;
}

// ─── Generation cache ─────────────────────────────────────────────────────────
// Identical input combos return cached results instead of re-calling the API.
// Module-level so cache persists across re-renders within a single session.
const GENERATION_CACHE = new Map();
const CACHE_MAX_SIZE = 100;

function cacheKey(form) {
  return JSON.stringify({
    a: `${form.ageMin}-${form.ageMax}`,
    o: form.occasion,
    b: form.bagStyle,
    c: form.count,
    bg: form.budget,
    f: form.includeFood,
    al: [...form.allergies].sort().join(","),
  });
}

function cacheGet(form) {
  const k = cacheKey(form);
  const hit = GENERATION_CACHE.get(k);
  if (!hit) return null;
  // Refresh recency by re-inserting (LRU-ish)
  GENERATION_CACHE.delete(k);
  GENERATION_CACHE.set(k, hit);
  return hit;
}

function cacheSet(form, bag) {
  const k = cacheKey(form);
  GENERATION_CACHE.set(k, bag);
  // Evict oldest entries if we exceed max size
  while (GENERATION_CACHE.size > CACHE_MAX_SIZE) {
    const firstKey = GENERATION_CACHE.keys().next().value;
    GENERATION_CACHE.delete(firstKey);
  }
}

